def nearest_airport(
    latitude: Any, longitude: Any, candidates: Iterable[str]
) -> str | None:
    """Rank known candidates locally by great-circle distance; ties use code."""
    for value, limit in ((latitude, 90), (longitude, 180)):
        if (
            isinstance(value, bool)
            or not isinstance(value, (int, float))
            or not math.isfinite(value)
            or not -limit <= value <= limit
        ):
            return None
    lat, lon = math.radians(latitude), math.radians(longitude)
    ranked = []
    for code in candidates:
        if code not in COORDINATES:
            continue
        other_lat, other_lon = map(math.radians, COORDINATES[code])
        # Haversine's central-angle term is monotonic on [0, pi].
        distance = (
            math.sin((other_lat - lat) / 2) ** 2
            + math.cos(lat) * math.cos(other_lat) * math.sin((other_lon - lon) / 2) ** 2
        )
        ranked.append((distance, code))
    return min(ranked)[1] if ranked else None
